package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

const defaultReportDir = "experiments/policy-bypass/reports"
const defaultReportName = "EXPERIMENT-REPORT.md"

var reportPath = defaultReportDir + "/" + defaultReportName

// writeReport produces the findings report consumed by the audit workflow.
func writeReport(results []Result) error {
	var b strings.Builder
	fmt.Fprintf(&b, "# NAEOS Policy Bypass Experiment Report\n\n")
	fmt.Fprintf(&b, "Run: %s\n\n", time.Now().UTC().Format(time.RFC3339))
	b.WriteString("Method: deterministic Go harness exercising the real NAEOS " +
		"governance, control-plane, reviewer, prompt, and pipeline code paths. " +
		"No live LLM is used; each scenario simulates what an AI agent with " +
		"normal repository write access can achieve.\n\n")

	var failures, bypasses, notEvaluated int
	for _, r := range results {
		if r.Verdict == VerdictFail {
			failures++
		}
		if r.ObservedOutcome == OutcomeAllow {
			bypasses++
		}
		if r.ObservedOutcome == OutcomeNotEvaluated {
			notEvaluated++
		}
	}
	fmt.Fprintf(&b, "## Result: %d oracle failures / %d bypasses / %d not-evaluated\n\n", failures, bypasses, notEvaluated)

	byLayer := map[Layer][]Result{}
	for _, r := range results {
		byLayer[r.Layer] = append(byLayer[r.Layer], r)
	}
	order := []Layer{LayerEvaluator, LayerControl, LayerReviewer, LayerPrompt, LayerPipeline}
	b.WriteString("## Findings by layer\n\n")
	for _, l := range order {
		rs := byLayer[l]
		if len(rs) == 0 {
			continue
		}
		fmt.Fprintf(&b, "### %s\n\n", l)
		b.WriteString("| Scenario | Attack | Evidence | Expected | Observed | Verdict | Risk |\n")
		b.WriteString("|---|---|---|---|---|---|---|\n")
		for _, r := range rs {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\\n",
				r.Scenario, r.Attack, r.Evidence, r.ExpectedOutcome, r.ObservedOutcome, r.Verdict, r.Risk)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Findings detail\n\n")
	for _, r := range results {
		fmt.Fprintf(&b, "- **%s** [%s/%s] %s\n", r.Scenario, r.Layer, r.Risk, r.Attack)
	}
	b.WriteString("\n## Oracle notes\n\n")
	b.WriteString("`EXPECTED` is the governance invariant. `OBSERVED` is what the deterministic code path produced. `FAIL` means the observed behavior violates the invariant and is therefore a reproduced finding. `NOT_EVALUATED` is intentionally distinct from DENY: it means the policy did not receive the data it claimed to govern.\n\n")
	b.WriteString("\n---\n\n_Generated by experiments/policy-bypass. Findings are characterization results; remediation status is tracked separately._\n")

	if err := os.MkdirAll(filepath.Dir(reportPath), 0o750); err != nil {
		return err
	}
	return os.WriteFile(reportPath, []byte(b.String()), 0o600)
}

func printResults(results []Result) {
	for _, r := range results {
		fmt.Println(r.String())
	}
	summarize(results)
}
